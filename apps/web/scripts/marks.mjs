/**
 * Writes every asset and venue mark Mitoshi shows into public/marks/, plus the manifest the <Mark> component reads.
 * Run it by hand (`pnpm marks`) when the venues list new assets; the output is committed, so builds never fetch.
 *
 * Coins come from @web3icons/core (MIT, the "background" set: a coloured square, which the app rounds into a disc),
 * and, for coins it lacks, Hyperliquid's own icon (vendored here, never loaded from Hyperliquid at runtime).
 * The symbols are Hyperliquid's live perp universe plus a base set for Solana and the rails. Venue marks are the
 * vendored files in scripts/venues/ (see SOURCES.md) and web3icons' network marks.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const APP = new URL("..", import.meta.url).pathname;
const ICONS = join(realpathSync(join(APP, "node_modules/@web3icons/core")), "dist/svgs");
const OUT = join(APP, "public/marks");
const MANIFEST = join(APP, "src/features/marks/manifest.generated.ts");

const BASE = [
  "ZEC",
  "USDC",
  "USDT",
  "SOL",
  "BTC",
  "ETH",
  "POL",
  "NEAR",
  "JUP",
  "BONK",
  "WIF",
  "JTO",
  "PYTH",
  "RAY",
  "ORCA",
  "TRUMP",
  "PENGU",
  "FARTCOIN",
  "POPCAT",
  "RENDER",
  "HNT",
  "W",
  "MEW",
  "GRASS",
  "DRIFT",
  "KMNO",
  "TNSR",
  "ZEUS",
];

/** Venue (and rail) marks: our file name → web3icons network, or a vendored file. */
const VENUES = {
  hyperliquid: { network: "hyper-evm" },
  solana: { network: "solana" },
  near: { network: "near-protocol" },
  polygon: { network: "polygon" },
  zcash: { token: "ZEC" },
  polymarket: { file: "scripts/venues/polymarket.svg" },
  jupiter: { file: "scripts/venues/jupiter.svg" },
};

async function svg(kind, name) {
  const f = join(ICONS, kind, "background", `${name}.svg.js`);
  if (!existsSync(f)) return null;
  return (await import(f)).default;
}

/** Hyperliquid's coin names ("kPEPE" is 1,000 PEPE: the mark is PEPE's). */
async function hyperliquidCoins() {
  const res = await fetch("https://api.hyperliquid.xyz/info", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ type: "meta" }),
  });
  const meta = await res.json();
  return meta.universe.filter((u) => !u.isDelisted).map((u) => u.name);
}

/** Marks above this are traced bitmaps: they are rasterised to a small PNG (rsvg-convert) instead. */
const MARK_MAX_BYTES = 49_152; // 48 KiB
const RASTER_PX = 96;
/** rsvg-convert output can be a few MB for the largest traced marks. */
const RASTER_MAX_BUFFER = 67_108_864; // 64 MiB

function rasterise(svgText) {
  return execFileSync("rsvg-convert", ["-w", String(RASTER_PX), "-h", String(RASTER_PX), "-f", "png"], {
    input: svgText,
    maxBuffer: RASTER_MAX_BUFFER,
  });
}

const markName = (coin) => (/^k[A-Z]/.test(coin) ? coin.slice(1) : coin).toUpperCase();

/** Hyperliquid's own coin icon, for coins web3icons lacks (only kept when it really is an SVG). */
async function hyperliquidIcon(coin) {
  for (const name of [coin, markName(coin)]) {
    const res = await fetch(`https://app.hyperliquid.xyz/coins/${encodeURIComponent(name)}.svg`);
    const type = res.headers.get("content-type") ?? "";
    const body = await res.text();
    if (res.ok && type.includes("image/svg") && body.includes("<svg")) return body;
  }
  return null;
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const coins = await hyperliquidCoins();
const symbols = [...new Set([...BASE, ...coins.map(markName)])].sort();
const have = [];
const fromHyperliquid = [];
const raster = [];
for (const s of symbols) {
  let body = await svg("tokens", s);
  if (!body) {
    const coin = coins.find((c) => markName(c) === s);
    body = coin ? await hyperliquidIcon(coin) : null;
    if (body) fromHyperliquid.push(s);
  }
  if (!body) continue;
  if (Buffer.byteLength(body) > MARK_MAX_BYTES) {
    writeFileSync(join(OUT, `${s}.png`), rasterise(body));
    raster.push(s);
  } else {
    writeFileSync(join(OUT, `${s}.svg`), body);
  }
  have.push(s);
}
const venues = [];
for (const [name, src] of Object.entries(VENUES)) {
  const body = src.file
    ? readFileSync(join(APP, src.file), "utf8")
    : await svg(src.network ? "networks" : "tokens", src.network ?? src.token);
  if (!body) throw new Error(`no mark for venue ${name}`);
  writeFileSync(join(OUT, `venue-${name}.svg`), body);
  venues.push(name);
}
writeFileSync(
  MANIFEST,
  `// Generated by scripts/marks.mjs. Do not edit.\n` +
    `/** Coin symbols with a mark in public/marks/<SYMBOL>.svg. */\n` +
    `export const COIN_MARKS: ReadonlySet<string> = new Set(${JSON.stringify(have)});\n\n` +
    `/** Of those, the ones stored as public/marks/<SYMBOL>.png (rasterised traced bitmaps). */\n` +
    `export const RASTER_MARKS: ReadonlySet<string> = new Set(${JSON.stringify(raster)});\n\n` +
    `/** Venue marks in public/marks/venue-<name>.svg. */\n` +
    `export const VENUE_MARKS = ${JSON.stringify(venues)} as const;\n`,
);
console.log(
  `marks: ${have.length} of ${symbols.length} coins (${fromHyperliquid.length} from Hyperliquid), ${venues.length} venues`,
);
